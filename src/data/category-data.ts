const createCards = (slug: string, title: string, imagePool: string[]): DecorCard[] => {
	const baseTitle = title.trim();
	return imagePool.map((image, index) => {
		let cardTitle = '';
		if (slug === 'birthday-decoration') {
			cardTitle = `Birthday ${index + 1}`;
		} else if (slug === 'kids-theme-decoration') {
			cardTitle = `KID ${index + 1}`;
		} else if (slug === 'welcome-baby-decoration') {
			cardTitle = `Welcome Baby ${index + 1}`;
		} else if (slug === 'anniversary-decoration') {
			cardTitle = `Anniversary ${index + 1}`;
		} else if (slug === 'romantic-room-decoration') {
			cardTitle = `Room Decor ${index + 1}`;
		} else if (slug === 'proposal-decoration') {
			cardTitle = `Proposal ${index + 1}`;
		} else if (slug === 'car-decoration') {
			cardTitle = `Car Boot ${index + 1}`;
		} else if (slug === 'festival-decoration') {
			cardTitle = `Festival ${index + 1}`;
		} else if (slug === 'corporate-office-decoration') {
			cardTitle = `Corporate ${index + 1}`;
		} else if (slug === 'shop-opening-decoration') {
			cardTitle = `Shop Opening ${index + 1}`;
		} else if (slug === 'balloon-hampers') {
			cardTitle = `Balloon Hamper ${index + 1}`;
		} else if (slug === 'baby-shower-decoration') {
			cardTitle = `Baby Shower ${index + 1}`;
		} else if (slug === 'bachelorette-decoration') {
			cardTitle = `Bachelorette ${index + 1}`;
		} else {
			cardTitle = `${baseTitle} ${index + 1}`;
		}
		return {
			id: `${slug}-card-${index + 1}`,
			title: cardTitle,
			image: image,
			rating: ['4.9', '4.8', '5.0', '4.7'][index % 4],
			reviews: [120, 85, 200, 140, 95][index % 5],
			tags: index % 2 === 0 ? ['Indoor', 'Theme Based'] : ['Premium', 'Popular'],
		};
	});
};


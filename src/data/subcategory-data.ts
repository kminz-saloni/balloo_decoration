const createCards = (slug: string, title: string, imagePool: string[]): SubCategoryCard[] => {
	const baseTitle = title.trim();

	if (!imagePool || imagePool.length === 0) return [];

	return imagePool.map((imagePath, index) => {
		const parts = imagePath.split('https://camsstorage2026abcd.blob.core.windows.net/balooon/');
		const filename = decodeURIComponent(parts[parts.length - 1] || '');
		let cardTitle = filename.replace(/\.[^/.]+$/, "").trim();
		if (!cardTitle || cardTitle.match(/^\d+$/) || cardTitle.toLowerCase() === 'image' || cardTitle.toLowerCase() === 'thumb') {
			cardTitle = `${baseTitle} ${cardTitleTemplates[index % cardTitleTemplates.length]}`;
		}
		
		return {
			id: `${slug}-${index + 1}`,
			title: cardTitle,
			image: imagePath,
			rating: cardRatingTemplates[index % cardRatingTemplates.length],
			reviews: cardReviewTemplates[index % cardReviewTemplates.length],
			tags: cardTagTemplates[index % cardTagTemplates.length],
		};
	});
};

